#!/bin/sh
# embed_fixtures.sh -- fixtures as const arrays, for the bare-metal proof
# (make test-baremetal-qemu, bd-9kll.15.7).
#
# The proof images have no file system, so every fixture they replay is
# compiled in. This writes one C file:
#
#   static const unsigned char bm_fx_<n>[] = { ...the file's bytes... };
#   const bm_fixture g_bm_fixtures[] = { {bm_fx_0, sizeof bm_fx_0}, ... };
#   const unsigned g_bm_fixture_count = <n>;
#
# in the order of the arguments (tools/baremetal/bm_main.c replays them in
# that order and prints one line each, as `asx-conformance replay` does for
# the same files in the same order).
#
# Usage: embed_fixtures.sh OUT.c [--corrupt ID] FIXTURE.json...
#
# --corrupt ID is the planted control: the first digit after a `"ns":` in
# the fixture whose file name is ID.json is raised by one (9 wraps to 0),
# one byte, in the scenario the interpreter runs; the corrupted copy is kept
# next to OUT.c as corrupted-ID.json and is what is embedded in its place.
# A run of that image must differ from the host's on that fixture's line and
# on no other (tools/baremetal/compare_replay.sh --expect-differ ID).
#
# Needs only POSIX sh, od, sed, grep, dd, head and tail.
#
# SPDX-License-Identifier: MIT

set -eu

[ $# -ge 2 ] || { echo "usage: embed_fixtures.sh OUT.c [--corrupt ID] FIXTURE.json..." >&2; exit 2; }
out=$1
shift
corrupt=
if [ "$1" = "--corrupt" ]; then
    [ $# -ge 3 ] || { echo "embed_fixtures: --corrupt needs an id" >&2; exit 2; }
    corrupt=$2
    shift 2
fi
[ $# -ge 1 ] || { echo "embed_fixtures: no fixtures" >&2; exit 2; }
out_dir=$(dirname "$out")
mkdir -p "$out_dir"

{
    echo "/* Generated by tools/baremetal/embed_fixtures.sh; do not edit. */"
    echo "#include <stddef.h>"
    echo ""
    echo "typedef struct {"
    echo "    const unsigned char *data;"
    echo "    size_t len;"
    echo "} bm_fixture;"
    echo ""
} > "$out"

n=0
planted=0
for f in "$@"; do
    src=$f
    id=$(basename "$f" .json)
    if [ -n "$corrupt" ] && [ "$id" = "$corrupt" ]; then
        # The byte offset of the match start, then the digit after `"ns":`.
        off=$(grep -a -b -o -m1 '"ns":[0-9]' "$f" | head -n 1 | cut -d: -f1)
        if [ -z "$off" ]; then
            echo "embed_fixtures: no \"ns\":<digit> in $f to corrupt" >&2
            exit 1
        fi
        pos=$((off + 5))
        old=$(dd if="$f" bs=1 skip="$pos" count=1 2>/dev/null)
        new=$(( (old + 1) % 10 ))
        src="$out_dir/corrupted-$id.json"
        { head -c "$pos" "$f"; printf '%s' "$new"; tail -c +$((pos + 2)) "$f"; } > "$src"
        echo "embed_fixtures: planted control: $id byte $pos \"$old\" -> \"$new\"" >&2
        planted=1
    fi
    {
        echo "static const unsigned char bm_fx_${n}[] = {"
        od -An -v -tu1 -w16 "$src" | sed -e 's/^ *//' -e 's/  */,/g' -e 's/$/,/'
        echo "};"
    } >> "$out"
    n=$((n + 1))
done

if [ -n "$corrupt" ] && [ "$planted" -eq 0 ]; then
    echo "embed_fixtures: --corrupt $corrupt names no fixture of the list" >&2
    exit 1
fi

{
    echo ""
    echo "const bm_fixture g_bm_fixtures[] = {"
    i=0
    while [ "$i" -lt "$n" ]; do
        echo "    {bm_fx_$i, sizeof(bm_fx_$i)},"
        i=$((i + 1))
    done
    echo "};"
    echo "const unsigned g_bm_fixture_count = $n;"
} >> "$out"
