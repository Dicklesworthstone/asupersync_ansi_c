static void rq_partition(uint32_t i, uint32_t j, asx_raptorq_partition *out) {
    out->small_size = i / j;
    out->large_size = out->small_size + (i % j != 0u ? 1u : 0u);
    out->large_count = i - out->small_size * j;
    out->small_count = j - out->large_count;
}

asx_status asx_raptorq_partition_compute(uint32_t i, uint32_t j, asx_raptorq_partition *out) {
    if (out == NULL || j == 0u) return ASX_E_INVALID_ARGUMENT;
    rq_partition(i, j, out);
    return ASX_OK;
}

static uint64_t rq_div_ceil_u64(uint64_t a, uint64_t b) { return a / b + (a % b != 0u ? 1u : 0u); }

asx_status asx_raptorq_oti_validate(const asx_raptorq_oti *oti) {
    uint64_t kt;
    uint32_t t;
    uint32_t al;
    if (oti == NULL) return ASX_E_INVALID_ARGUMENT;
    t = oti->symbol_size;
    al = oti->alignment;
    if (oti->transfer_length == 0u || oti->transfer_length > ASX_RAPTORQ_MAX_TRANSFER_LENGTH) {
        return ASX_E_INVALID_ARGUMENT;
    }
    if (t == 0u || al == 0u || t % al != 0u) return ASX_E_INVALID_ARGUMENT;
    if (oti->sub_blocks == 0u || (uint32_t)oti->sub_blocks > t / al) return ASX_E_INVALID_ARGUMENT;
    if (oti->source_blocks == 0u) return ASX_E_INVALID_ARGUMENT;
    kt = rq_div_ceil_u64(oti->transfer_length, t);
    if ((uint64_t)oti->source_blocks > kt) return ASX_E_INVALID_ARGUMENT;
    if (rq_div_ceil_u64(kt, oti->source_blocks) > ASX_RAPTORQ_MAX_SOURCE_SYMBOLS) {
        return ASX_E_INVALID_ARGUMENT;
    }
    return ASX_OK;
}

asx_status asx_raptorq_oti_init(asx_raptorq_oti *oti, uint64_t transfer_length,
                                uint16_t symbol_size, uint8_t alignment,
                                uint32_t max_block_symbols) {
    asx_raptorq_oti o;
    uint64_t kt;
    uint64_t z;
    if (oti == NULL || max_block_symbols == 0u ||
        max_block_symbols > ASX_RAPTORQ_MAX_SOURCE_SYMBOLS || symbol_size == 0u ||
        transfer_length == 0u || transfer_length > ASX_RAPTORQ_MAX_TRANSFER_LENGTH) {
        return ASX_E_INVALID_ARGUMENT;
    }
    kt = rq_div_ceil_u64(transfer_length, symbol_size);
    z = rq_div_ceil_u64(kt, max_block_symbols);
    if (z > ASX_RAPTORQ_MAX_SOURCE_BLOCKS) return ASX_E_INVALID_ARGUMENT;
    memset(&o, 0, sizeof(o));
    o.transfer_length = transfer_length;
    o.symbol_size = symbol_size;
    o.sub_blocks = 1u;
    o.source_blocks = (uint8_t)z;
    o.alignment = alignment;
    if (asx_raptorq_oti_validate(&o) != ASX_OK) return ASX_E_INVALID_ARGUMENT;
    *oti = o;
    return ASX_OK;
}

asx_status asx_raptorq_oti_serialize(const asx_raptorq_oti *oti,
                                     uint8_t out[ASX_RAPTORQ_OTI_SIZE]) {
    uint64_t f;
    if (out == NULL || asx_raptorq_oti_validate(oti) != ASX_OK) return ASX_E_INVALID_ARGUMENT;
    f = oti->transfer_length;
    out[0] = (uint8_t)((f >> 32) & 0xFFu);
    out[1] = (uint8_t)((f >> 24) & 0xFFu);
    out[2] = (uint8_t)((f >> 16) & 0xFFu);
    out[3] = (uint8_t)((f >> 8) & 0xFFu);
    out[4] = (uint8_t)(f & 0xFFu);
    out[5] = 0u;
    out[6] = (uint8_t)((oti->symbol_size >> 8) & 0xFFu);
    out[7] = (uint8_t)(oti->symbol_size & 0xFFu);
    out[8] = oti->source_blocks;
    out[9] = (uint8_t)((oti->sub_blocks >> 8) & 0xFFu);
    out[10] = (uint8_t)(oti->sub_blocks & 0xFFu);
    out[11] = oti->alignment;
    return ASX_OK;
}

asx_status asx_raptorq_oti_deserialize(const uint8_t in[ASX_RAPTORQ_OTI_SIZE],
                                       asx_raptorq_oti *out) {
    asx_raptorq_oti o;
    if (in == NULL || out == NULL || in[5] != 0u) return ASX_E_INVALID_ARGUMENT;
    memset(&o, 0, sizeof(o));
    o.transfer_length = ((uint64_t)in[0] << 32) | ((uint64_t)in[1] << 24) |
                        ((uint64_t)in[2] << 16) | ((uint64_t)in[3] << 8) | (uint64_t)in[4];
    o.symbol_size = (uint16_t)(((uint32_t)in[6] << 8) | (uint32_t)in[7]);
    o.source_blocks = in[8];
    o.sub_blocks = (uint16_t)(((uint32_t)in[9] << 8) | (uint32_t)in[10]);
    o.alignment = in[11];
    if (asx_raptorq_oti_validate(&o) != ASX_OK) return ASX_E_INVALID_ARGUMENT;
    *out = o;
    return ASX_OK;
}

asx_status asx_raptorq_oti_block_layout(const asx_raptorq_oti *oti, uint32_t sbn,
                                        asx_raptorq_block_layout *out) {
    asx_raptorq_partition part;
    uint64_t first;
    uint64_t bytes;
    uint32_t kt;
    if (out == NULL || asx_raptorq_oti_validate(oti) != ASX_OK) return ASX_E_INVALID_ARGUMENT;
    if (sbn >= oti->source_blocks) return ASX_E_INVALID_ARGUMENT;
    /* Validation bounds Kt by Z * K'max, so it fits in 32 bits. */
    kt = (uint32_t)rq_div_ceil_u64(oti->transfer_length, oti->symbol_size);
    rq_partition(kt, oti->source_blocks, &part);
    memset(out, 0, sizeof(*out));
    if (sbn < part.large_count) {
        out->source_symbols = part.large_size;
        first = (uint64_t)sbn * part.large_size;
    } else {
        out->source_symbols = part.small_size;
        first = (uint64_t)part.large_count * part.large_size +
                (uint64_t)(sbn - part.large_count) * part.small_size;
    }
    out->symbol_size = oti->symbol_size;
    out->offset = first * oti->symbol_size;
    bytes = (uint64_t)out->source_symbols * oti->symbol_size;
    out->length =
        oti->transfer_length - out->offset < bytes ? oti->transfer_length - out->offset : bytes;
    return ASX_OK;
}

/* Shared argument checks for gather/scatter. */
static asx_status rq_block_io_check(const asx_raptorq_oti *oti, uint32_t sbn, size_t object_len,
                                    size_t block_len, asx_raptorq_block_layout *lay) {
    asx_status st = asx_raptorq_oti_block_layout(oti, sbn, lay);
    if (st != ASX_OK) return st;
    if ((uint64_t)object_len < oti->transfer_length) return ASX_E_BUFFER_TOO_SMALL;
    if ((uint64_t)block_len < (uint64_t)lay->source_symbols * lay->symbol_size) {
        return ASX_E_BUFFER_TOO_SMALL;
    }
    return ASX_OK;
}

/* Walk every sub-symbol of a block: object position <-> block position.
 * gather != 0 copies object -> block (zero padding past F); otherwise
 * copies block -> object (bytes past F are dropped). */
static void rq_block_walk(const asx_raptorq_oti *oti, const asx_raptorq_block_layout *lay,
                          uint8_t *object, const uint8_t *object_in, uint8_t *block,
                          const uint8_t *block_in, int gather) {
    asx_raptorq_partition sub;
    uint64_t f = oti->transfer_length;
    uint64_t sb_base = lay->offset;
    size_t sym_off = 0u;
    size_t t = oti->symbol_size;
    uint32_t nsub;
    uint32_t i;

    rq_partition((uint32_t)oti->symbol_size / oti->alignment, oti->sub_blocks, &sub);
    for (nsub = 0u; nsub < oti->sub_blocks; nsub++) {
        size_t sz =
            (size_t)(nsub < sub.large_count ? sub.large_size : sub.small_size) * oti->alignment;
        for (i = 0u; i < lay->source_symbols; i++) {
            uint64_t pos = sb_base + (uint64_t)i * sz;
            size_t avail = 0u;
            size_t bpos = (size_t)i * t + sym_off;
            if (pos < f) avail = (f - pos) < (uint64_t)sz ? (size_t)(f - pos) : sz;
            if (gather) {
                if (avail > 0u) memcpy(block + bpos, object_in + (size_t)pos, avail);
                if (avail < sz) memset(block + bpos + avail, 0, sz - avail);
            } else if (avail > 0u) {
                memcpy(object + (size_t)pos, block_in + bpos, avail);
            }
        }
        sb_base += (uint64_t)lay->source_symbols * sz;
        sym_off += sz;
    }
}

asx_status asx_raptorq_block_gather(const asx_raptorq_oti *oti, uint32_t sbn, const uint8_t *object,
                                    size_t object_len, uint8_t *block_out, size_t block_out_len) {
    asx_raptorq_block_layout lay;
    asx_status st;
    if (object == NULL || block_out == NULL) return ASX_E_INVALID_ARGUMENT;
    st = rq_block_io_check(oti, sbn, object_len, block_out_len, &lay);
    if (st != ASX_OK) return st;
    rq_block_walk(oti, &lay, NULL, object, block_out, NULL, 1);
    return ASX_OK;
}

asx_status asx_raptorq_block_scatter(const asx_raptorq_oti *oti, uint32_t sbn, const uint8_t *block,
                                     size_t block_len, uint8_t *object_out, size_t object_len) {
    asx_raptorq_block_layout lay;
    asx_status st;
    if (block == NULL || object_out == NULL) return ASX_E_INVALID_ARGUMENT;
    st = rq_block_io_check(oti, sbn, object_len, block_len, &lay);
    if (st != ASX_OK) return st;
    rq_block_walk(oti, &lay, object_out, NULL, NULL, block, 0);
    return ASX_OK;
}
