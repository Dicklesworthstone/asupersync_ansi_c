static int rq_symbol_size_valid(uint32_t symbol_size) {
    return symbol_size >= 1u && symbol_size <= ASX_RAPTORQ_MAX_SYMBOL_SIZE;
}

static asx_status rq_encoder_layout(const asx_raptorq_params *p, uint32_t symbol_size, void *ws,
                                    size_t ws_size, rq_solver *sv, size_t *out_used) {
    rq_arena a;
    asx_status st;
    rq_arena_init(&a, ws, ws_size);
    st = rq_solver_carve(&a, p, symbol_size, p->k_prime, sv);
    if (st == ASX_E_RESOURCE_EXHAUSTED && ws != NULL) return ASX_E_BUFFER_TOO_SMALL;
    if (st != ASX_OK) return st;
    *out_used = a.used;
    return ASX_OK;
}

asx_status asx_raptorq_encoder_workspace_size(uint32_t k, uint32_t symbol_size, size_t *out_size) {
    asx_raptorq_params prm;
    rq_solver sv;
    asx_status st;
    if (out_size == NULL) return ASX_E_INVALID_ARGUMENT;
    *out_size = 0u;
    if (!rq_symbol_size_valid(symbol_size)) return ASX_E_INVALID_ARGUMENT;
    st = asx_raptorq_params_init(k, &prm);
    if (st != ASX_OK) return st;
    return rq_encoder_layout(&prm, symbol_size, NULL, 0u, &sv, out_size);
}

asx_status asx_raptorq_encoder_init(asx_raptorq_encoder *enc, uint32_t k, uint32_t symbol_size,
                                    const uint8_t *source, size_t source_len, void *workspace,
                                    size_t workspace_size) {
    asx_raptorq_params prm;
    rq_solver sv;
    size_t need;
    size_t used;
    uint32_t i;
    asx_status st;

    if (enc == NULL) return ASX_E_INVALID_ARGUMENT;
    memset(enc, 0, sizeof(*enc));
    if (source == NULL || workspace == NULL || !rq_symbol_size_valid(symbol_size)) {
        return ASX_E_INVALID_ARGUMENT;
    }
    st = asx_raptorq_params_init(k, &prm);
    if (st != ASX_OK) return st;
    if (source_len == 0u || source_len / symbol_size > k ||
        (source_len / symbol_size == k && source_len % symbol_size != 0u)) {
        return ASX_E_INVALID_ARGUMENT;
    }
    st = asx_raptorq_encoder_workspace_size(k, symbol_size, &need);
    if (st != ASX_OK) return st;
    if (workspace_size < need) return ASX_E_BUFFER_TOO_SMALL;
    st = rq_encoder_layout(&prm, symbol_size, workspace, workspace_size, &sv, &used);
    if (st != ASX_OK) return st;

    /* LT rows: ISIs 0..K-1 carry source symbols, K..K'-1 are zero padding. */
    for (i = 0u; i < prm.k_prime; i++) {
        size_t off = (size_t)i * symbol_size;
        sv.src[i].isi = i;
        if (i < k && off < source_len) {
            size_t avail = source_len - off;
            sv.src[i].data = source + off;
            sv.src[i].len = avail < symbol_size ? avail : symbol_size;
        } else {
            sv.src[i].data = NULL;
            sv.src[i].len = 0u;
        }
    }
    sv.prm = &prm;
    st = rq_solve(&sv);
    if (st != ASX_OK) {
        /* The RFC 6330 constraint matrix is always invertible for K'. */
        return st == ASX_E_RESOURCE_EXHAUSTED ? ASX_E_INVALID_STATE : st;
    }
    enc->params = prm;
    enc->symbol_size = symbol_size;
    enc->intermediate = sv.inter;
    enc->ready = RQ_READY;
    return ASX_OK;
}

asx_status asx_raptorq_encoder_symbol(const asx_raptorq_encoder *enc, uint32_t esi, uint8_t *out,
                                      size_t out_len) {
    uint32_t isi;
    if (enc == NULL || out == NULL || esi > ASX_RAPTORQ_MAX_ESI) return ASX_E_INVALID_ARGUMENT;
    if (enc->ready != RQ_READY || enc->intermediate == NULL) return ASX_E_INVALID_STATE;
    if (out_len < enc->symbol_size) return ASX_E_BUFFER_TOO_SMALL;
    isi = esi < enc->params.k ? esi : esi + (enc->params.k_prime - enc->params.k);
    rq_enc(&enc->params, enc->intermediate, enc->symbol_size, isi, out);
    return ASX_OK;
}

