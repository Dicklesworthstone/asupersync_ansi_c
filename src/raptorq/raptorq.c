/* ------------------------------------------------------------------ */
/* GF(256) arithmetic (RFC 6330 section 5.7)                           */
/* ------------------------------------------------------------------ */

static uint8_t rq_gf_mul(uint8_t a, uint8_t b) {
    if (a == 0u || b == 0u) return 0u;
    return rq_oct_exp[(uint32_t)rq_oct_log[a] + (uint32_t)rq_oct_log[b]];
}

/* Multiplicative inverse; a must be non-zero. */
static uint8_t rq_gf_inv(uint8_t a) { return rq_oct_exp[255u - (uint32_t)rq_oct_log[a]]; }

/* Multiply by alpha (= 2) modulo x^8 + x^4 + x^3 + x^2 + 1. */
static uint8_t rq_gf_mul2(uint8_t a) {
    uint32_t v = (uint32_t)a << 1;
    if ((v & 0x100u) != 0u) v ^= 0x11Du;
    return (uint8_t)v;
}

uint8_t asx_raptorq_gf256_mul(uint8_t a, uint8_t b) { return rq_gf_mul(a, b); }

uint8_t asx_raptorq_gf256_div(uint8_t a, uint8_t b) {
    if (a == 0u || b == 0u) return 0u;
    return rq_oct_exp[(uint32_t)rq_oct_log[a] + 255u - (uint32_t)rq_oct_log[b]];
}

uint8_t asx_raptorq_gf256_exp(uint32_t i) { return rq_oct_exp[i % 255u]; }

/* ------------------------------------------------------------------ */
/* Symbol (octet vector) operations                                    */
/* ------------------------------------------------------------------ */

static void rq_sym_xor(uint8_t *dst, const uint8_t *src, size_t n) {
    size_t i = 0u;
    while (i + 8u <= n) {
        uint64_t a;
        uint64_t b;
        memcpy(&a, dst + i, sizeof(a));
        memcpy(&b, src + i, sizeof(b));
        a ^= b;
        memcpy(dst + i, &a, sizeof(a));
        i += 8u;
    }
    for (; i < n; i++) dst[i] ^= src[i];
}

/* dst += f * src over GF(256). */
static void rq_sym_muladd(uint8_t *dst, const uint8_t *src, uint8_t f, size_t n) {
    size_t i;
    if (f == 0u) return;
    if (f == 1u) {
        rq_sym_xor(dst, src, n);
        return;
    }
    if (n < 64u) {
        uint32_t lf = rq_oct_log[f];
        for (i = 0u; i < n; i++) {
            if (src[i] != 0u) dst[i] ^= rq_oct_exp[lf + (uint32_t)rq_oct_log[src[i]]];
        }
    } else {
        uint8_t tab[256];
        uint32_t x;
        uint32_t lf = rq_oct_log[f];
        tab[0] = 0u;
        for (x = 1u; x < 256u; x++) tab[x] = rq_oct_exp[lf + (uint32_t)rq_oct_log[x]];
        for (i = 0u; i < n; i++) dst[i] ^= tab[src[i]];
    }
}

/* dst = f * dst over GF(256). */
static void rq_sym_scale(uint8_t *dst, uint8_t f, size_t n) {
    size_t i;
    if (f == 1u) return;
    if (f == 0u) {
        memset(dst, 0, n);
        return;
    }
    for (i = 0u; i < n; i++) dst[i] = rq_gf_mul(dst[i], f);
}

/* dst = alpha * dst over GF(256). */
static void rq_sym_mul2(uint8_t *dst, size_t n) {
    size_t i;
    for (i = 0u; i < n; i++) dst[i] = rq_gf_mul2(dst[i]);
}

/* ------------------------------------------------------------------ */
/* GF(2) bit vectors                                                   */
/* ------------------------------------------------------------------ */

static void rq_bits_xor(uint64_t *dst, const uint64_t *src, size_t words) {
    size_t i;
    for (i = 0u; i < words; i++) dst[i] ^= src[i];
}

static int rq_bit_get(const uint64_t *v, uint32_t k) {
    return (int)((v[k >> 6] >> (k & 63u)) & 1u);
}

static void rq_bit_flip(uint64_t *v, uint32_t k) { v[k >> 6] ^= (uint64_t)1u << (k & 63u); }

/* Index of the lowest set bit of a non-zero word. */
static uint32_t rq_ctz64(uint64_t w) {
    uint32_t n = 0u;
    if ((w & UINT64_C(0xFFFFFFFF)) == 0u) {
        n += 32u;
        w >>= 32;
    }
    if ((w & UINT64_C(0xFFFF)) == 0u) {
        n += 16u;
        w >>= 16;
    }
    if ((w & UINT64_C(0xFF)) == 0u) {
        n += 8u;
        w >>= 8;
    }
    if ((w & UINT64_C(0xF)) == 0u) {
        n += 4u;
        w >>= 4;
    }
    if ((w & UINT64_C(0x3)) == 0u) {
        n += 2u;
        w >>= 2;
    }
    if ((w & UINT64_C(0x1)) == 0u) n += 1u;
    return n;
}

/* Lowest set bit of a bit vector, or RQ_NONE when the vector is zero. */
static uint32_t rq_bits_lowest(const uint64_t *v, size_t words) {
    size_t i;
    for (i = 0u; i < words; i++) {
        if (v[i] != 0u) return (uint32_t)(i * 64u) + rq_ctz64(v[i]);
    }
    return RQ_NONE;
}

/* ------------------------------------------------------------------ */
/* RFC 6330 generators (sections 5.3.5 and 5.6)                        */
/* ------------------------------------------------------------------ */

uint32_t asx_raptorq_rand(uint32_t y, uint32_t i, uint32_t m) {
    uint32_t x0 = (y + i) & 0xFFu;
    uint32_t x1 = ((y >> 8) + i) & 0xFFu;
    uint32_t x2 = ((y >> 16) + i) & 0xFFu;
    uint32_t x3 = ((y >> 24) + i) & 0xFFu;
    if (m == 0u) return 0u;
    return (rq_v0[x0] ^ rq_v1[x1] ^ rq_v2[x2] ^ rq_v3[x3]) % m;
}

uint32_t asx_raptorq_deg(uint32_t v, uint32_t w) {
    uint32_t d;
    if (v >= 1048576u || w < 3u) return 0u;
    for (d = 1u; d <= RQ_MAX_LT_DEGREE; d++) {
        if (v < rq_deg_f[d]) break;
    }
    return d < w - 2u ? d : w - 2u;
}

static int rq_is_prime(uint32_t n) {
    uint32_t d;
    if (n < 2u) return 0;
    if (n % 2u == 0u) return n == 2u;
    for (d = 3u; d <= n / d; d += 2u) {
        if (n % d == 0u) return 0;
    }
    return 1;
}

asx_status asx_raptorq_params_init(uint32_t k, asx_raptorq_params *out) {
    uint32_t lo = 0u;
    uint32_t hi = (uint32_t)(sizeof(rq_sys_table) / sizeof(rq_sys_table[0])) - 1u;
    const rq_sys_row *row;
    asx_raptorq_params prm;

    if (out == NULL) return ASX_E_INVALID_ARGUMENT;
    memset(out, 0, sizeof(*out));
    if (k == 0u || k > ASX_RAPTORQ_MAX_SOURCE_SYMBOLS) return ASX_E_INVALID_ARGUMENT;

    /* Smallest K' >= K (binary search over the ascending table). */
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2u;
        if ((uint32_t)rq_sys_table[mid].k_prime >= k) {
            hi = mid;
        } else {
            lo = mid + 1u;
        }
    }
    row = &rq_sys_table[lo];

    memset(&prm, 0, sizeof(prm));
    prm.k = k;
    prm.k_prime = row->k_prime;
    prm.j = row->j;
    prm.s = row->s;
    prm.h = row->h;
    prm.w = row->w;
    prm.l = prm.k_prime + prm.s + prm.h;
    prm.p = prm.l - prm.w;
    prm.u = prm.p - prm.h;
    prm.b = prm.w - prm.s;
    prm.p1 = prm.p;
    while (!rq_is_prime(prm.p1)) prm.p1++;
    *out = prm;
    return ASX_OK;
}

static int rq_params_valid(const asx_raptorq_params *p) {
    return p != NULL && p->k >= 1u && p->k <= p->k_prime &&
           p->k_prime <= ASX_RAPTORQ_MAX_SOURCE_SYMBOLS && p->w >= 3u && p->s >= 1u && p->h >= 2u &&
           p->h <= RQ_MAX_H && p->p >= 2u && p->p1 >= p->p && p->l == p->k_prime + p->s + p->h &&
           p->p == p->l - p->w && p->b == p->w - p->s;
}

static void rq_tuple(const asx_raptorq_params *p, uint32_t x, asx_raptorq_tuple *t) {
    uint32_t a_fac = 53591u + p->j * 997u;
    uint32_t b_fac;
    uint32_t y;
    if (a_fac % 2u == 0u) a_fac += 1u;
    b_fac = 10267u * (p->j + 1u);
    y = (uint32_t)(((uint64_t)b_fac + (uint64_t)x * (uint64_t)a_fac) & UINT64_C(0xFFFFFFFF));
    t->d = asx_raptorq_deg(asx_raptorq_rand(y, 0u, 1048576u), p->w);
    t->a = 1u + asx_raptorq_rand(y, 1u, p->w - 1u);
    t->b = asx_raptorq_rand(y, 2u, p->w);
    t->d1 = t->d < 4u ? 2u + asx_raptorq_rand(x, 3u, 2u) : 2u;
    t->a1 = 1u + asx_raptorq_rand(x, 4u, p->p1 - 1u);
    t->b1 = asx_raptorq_rand(x, 5u, p->p1);
}

asx_status asx_raptorq_tuple_compute(const asx_raptorq_params *params, uint32_t isi,
                                     asx_raptorq_tuple *out) {
    if (out == NULL || !rq_params_valid(params)) return ASX_E_INVALID_ARGUMENT;
    rq_tuple(params, isi, out);
    return ASX_OK;
}

/* Add a column to a row with GF(2) semantics: a repeated column cancels. */
static void rq_row_toggle(uint32_t *cols, uint32_t *count, uint32_t c) {
    uint32_t i;
    for (i = 0u; i < *count; i++) {
        if (cols[i] == c) {
            cols[i] = cols[*count - 1u];
            *count -= 1u;
            return;
        }
    }
    cols[*count] = c;
    *count += 1u;
}

/* Intermediate-symbol indices combined by Enc[] for internal symbol ID
 * `isi` (RFC 6330 section 5.3.5.3). Returns the number of indices. */
static uint32_t rq_lt_indices(const asx_raptorq_params *p, uint32_t isi,
                              uint32_t out[RQ_MAX_ROW_ENTRIES]) {
    asx_raptorq_tuple t;
    uint32_t n = 0u;
    uint32_t j;
    uint32_t b;
    uint32_t b1;

    rq_tuple(p, isi, &t);
    b = t.b;
    rq_row_toggle(out, &n, b);
    for (j = 1u; j < t.d; j++) {
        b = (b + t.a) % p->w;
        rq_row_toggle(out, &n, b);
    }
    b1 = t.b1;
    while (b1 >= p->p) b1 = (b1 + t.a1) % p->p1;
    rq_row_toggle(out, &n, p->w + b1);
    for (j = 1u; j < t.d1; j++) {
        b1 = (b1 + t.a1) % p->p1;
        while (b1 >= p->p) b1 = (b1 + t.a1) % p->p1;
        rq_row_toggle(out, &n, p->w + b1);
    }
    return n;
}

/* Enc[]: write the encoding symbol for `isi` from intermediate symbols. */
static void rq_enc(const asx_raptorq_params *p, const uint8_t *inter, size_t t, uint32_t isi,
                   uint8_t *out) {
    uint32_t idx[RQ_MAX_ROW_ENTRIES];
    uint32_t n = rq_lt_indices(p, isi, idx);
    uint32_t e;
    memset(out, 0, t);
    for (e = 0u; e < n; e++) rq_sym_xor(out, inter + (size_t)idx[e] * t, t);
}

/* Rows of G_LDPC,1 hit by intermediate symbol i (section 5.3.3.3), after
 * GF(2) cancellation of coinciding targets. Returns the count (0 when
 * s == 0, which validated parameters never produce). */
static uint32_t rq_ldpc_targets(uint32_t i, uint32_t s, uint32_t out[3]) {
    uint32_t a;
    uint32_t b0;
    uint32_t b1;
    uint32_t b2;
    if (s == 0u) return 0u;
    a = 1u + i / s;
    b0 = i % s;
    b1 = (b0 + a) % s;
    b2 = (b1 + a) % s;
    if (b0 == b1 && b1 == b2) {
        out[0] = b0;
        return 1u;
    }
    if (b0 == b1) {
        out[0] = b2;
        return 1u;
    }
    if (b0 == b2) {
        out[0] = b1;
        return 1u;
    }
    if (b1 == b2) {
        out[0] = b0;
        return 1u;
    }
    out[0] = b0;
    out[1] = b1;
    out[2] = b2;
    return 3u;
}

