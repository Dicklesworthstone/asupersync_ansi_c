/*
 * raptorq.c — RFC 6330 RaptorQ systematic encoder/decoder
 *
 * Implements the RaptorQ FEC scheme of RFC 6330 with bit-exact encoding
 * symbols: GF(256) octet arithmetic, the systematic index table, Rand/Deg/
 * Tuple generators, the LDPC/HDPC/LT constraint matrix, intermediate-symbol
 * generation, encoding-symbol generation for any ESI, decoding from any set
 * of received encoding symbols, and the OTI / source-block partitioning
 * helpers of section 4.4.1.
 *
 * Solver (sections 5.3.3.4 and 5.4): inactivation decoding.
 *   1. The binary rows (LDPC + LT) are held sparsely. Columns 0..W-1 start
 *      active; the P PI columns are permanently inactive. Rows with exactly
 *      one active column are peeled (that column is decided by the row);
 *      when none exist, the active column with the highest degree in a
 *      minimum-degree row is inactivated. This yields a lower-triangular
 *      pivot sequence plus an inactive column set I.
 *   2. Each decided column is expressed as a GF(2) combination of I
 *      (bit-packed), so every non-pivot binary row reduces to an equation
 *      over I. These are reduced into a GF(2) basis in RREF.
 *   3. If the binary basis does not cover I, the H dense HDPC rows are
 *      reduced over I using the MT * GAMMA recurrence (never materialising
 *      the dense rows) and the remaining free columns are solved by GF(256)
 *      Gauss-Jordan elimination.
 *   4. Forward substitution through the pivot sequence recovers all decided
 *      intermediate symbols.
 * Symbol work is O(nnz * T + |I|^2 * T); matrix work is bit-packed.
 *
 * Memory: no allocation. All scratch is carved from caller workspaces with
 * a deterministic bump layout whose size is queried up front.
 *
 * SPDX-License-Identifier: MIT
 */

