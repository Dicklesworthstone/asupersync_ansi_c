typedef struct {
    uint8_t *base; /* NULL while only measuring */
    size_t cap;
    size_t used;
    int failed;
} rq_arena;

static void rq_arena_init(rq_arena *a, void *base, size_t cap) {
    a->base = (uint8_t *)base;
    a->cap = cap;
    a->used = 0u;
    a->failed = 0;
}

/* Reserve count * elem bytes aligned to RQ_ALIGN. While measuring, the
 * worst-case alignment padding is charged so that carving any base address
 * never needs more than the measured size. */
static void *rq_take(rq_arena *a, size_t count, size_t elem) {
    size_t bytes;
    size_t pad;
    void *p;

    if (a->failed) return NULL;
    if (elem != 0u && count > SIZE_MAX / elem) {
        a->failed = 1;
        return NULL;
    }
    bytes = count * elem;
    if (a->base == NULL) {
        pad = RQ_ALIGN - 1u;
    } else {
        uintptr_t addr = (uintptr_t)(a->base + a->used);
        pad = (size_t)((RQ_ALIGN - (size_t)(addr % RQ_ALIGN)) % RQ_ALIGN);
    }
    if (pad > SIZE_MAX - a->used || bytes > SIZE_MAX - a->used - pad) {
        a->failed = 1;
        return NULL;
    }
    if (a->base != NULL && a->used + pad + bytes > a->cap) {
        a->failed = 1;
        return NULL;
    }
    p = a->base != NULL ? (void *)(a->base + a->used + pad) : NULL;
    a->used += pad + bytes;
    return p;
}

