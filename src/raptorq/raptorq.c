static uint32_t rq_hash_slots(uint32_t capacity) {
    uint32_t slots = 16u;
    while (slots < capacity * 2u) slots <<= 1;
    return slots;
}

static uint32_t rq_hash_of(uint32_t esi, uint32_t mask) {
    return (uint32_t)(((uint64_t)esi * UINT64_C(2654435761)) & UINT64_C(0xFFFFFFFF)) & mask;
}

typedef struct {
    uint32_t *esi;
    uint32_t *hash;
    uint8_t *symbols;
    uint8_t *solver;
    size_t solver_size;
} rq_decoder_regions;

static asx_status rq_decoder_layout(const asx_raptorq_params *p, uint32_t symbol_size,
                                    uint32_t capacity, void *ws, size_t ws_size,
                                    rq_decoder_regions *out, size_t *out_used) {
    rq_arena a;
    rq_arena m;
    rq_solver sv;
    asx_status st;
    uint32_t n = capacity + (p->k_prime - p->k);

    rq_arena_init(&m, NULL, 0u);
    st = rq_solver_carve(&m, p, symbol_size, n, &sv);
    if (st != ASX_OK) return st;

    rq_arena_init(&a, ws, ws_size);
    out->esi = (uint32_t *)rq_take(&a, capacity, sizeof(uint32_t));
    out->hash = (uint32_t *)rq_take(&a, rq_hash_slots(capacity), sizeof(uint32_t));
    out->symbols = (uint8_t *)rq_take(&a, capacity, symbol_size);
    out->solver = (uint8_t *)rq_take(&a, m.used, 1u);
    out->solver_size = m.used;
    if (a.failed) return ws == NULL ? ASX_E_RESOURCE_EXHAUSTED : ASX_E_BUFFER_TOO_SMALL;
    *out_used = a.used;
    return ASX_OK;
}

static asx_status rq_decoder_check_args(uint32_t k, uint32_t symbol_size, uint32_t max_symbols,
                                        asx_raptorq_params *prm) {
    asx_status st;
    if (!rq_symbol_size_valid(symbol_size)) return ASX_E_INVALID_ARGUMENT;
    st = asx_raptorq_params_init(k, prm);
    if (st != ASX_OK) return st;
    if (max_symbols < k || max_symbols > ASX_RAPTORQ_MAX_ESI + 1u) return ASX_E_INVALID_ARGUMENT;
    return ASX_OK;
}

asx_status asx_raptorq_decoder_workspace_size(uint32_t k, uint32_t symbol_size,
                                              uint32_t max_symbols, size_t *out_size) {
    asx_raptorq_params prm;
    rq_decoder_regions reg;
    asx_status st;
    if (out_size == NULL) return ASX_E_INVALID_ARGUMENT;
    *out_size = 0u;
    st = rq_decoder_check_args(k, symbol_size, max_symbols, &prm);
    if (st != ASX_OK) return st;
    return rq_decoder_layout(&prm, symbol_size, max_symbols, NULL, 0u, &reg, out_size);
}

asx_status asx_raptorq_decoder_init(asx_raptorq_decoder *dec, uint32_t k, uint32_t symbol_size,
                                    uint32_t max_symbols, void *workspace, size_t workspace_size) {
    asx_raptorq_params prm;
    rq_decoder_regions reg;
    size_t need;
    size_t used;
    uint32_t slots;
    asx_status st;

    if (dec == NULL) return ASX_E_INVALID_ARGUMENT;
    memset(dec, 0, sizeof(*dec));
    if (workspace == NULL) return ASX_E_INVALID_ARGUMENT;
    st = rq_decoder_check_args(k, symbol_size, max_symbols, &prm);
    if (st != ASX_OK) return st;
    st = asx_raptorq_decoder_workspace_size(k, symbol_size, max_symbols, &need);
    if (st != ASX_OK) return st;
    if (workspace_size < need) return ASX_E_BUFFER_TOO_SMALL;
    st = rq_decoder_layout(&prm, symbol_size, max_symbols, workspace, workspace_size, &reg, &used);
    if (st != ASX_OK) return st;

    slots = rq_hash_slots(max_symbols);
    memset(reg.hash, 0, (size_t)slots * sizeof(uint32_t));
    dec->params = prm;
    dec->symbol_size = symbol_size;
    dec->capacity = max_symbols;
    dec->count = 0u;
    dec->source_count = 0u;
    dec->hash_mask = slots - 1u;
    dec->esi = reg.esi;
    dec->hash = reg.hash;
    dec->symbols = reg.symbols;
    dec->solver = reg.solver;
    dec->solver_size = reg.solver_size;
    dec->ready = RQ_READY;
    return ASX_OK;
}

/* Stored index of `esi`, or RQ_NONE. */
static uint32_t rq_decoder_find(const asx_raptorq_decoder *dec, uint32_t esi) {
    uint32_t h = rq_hash_of(esi, dec->hash_mask);
    for (;;) {
        uint32_t v = dec->hash[h];
        if (v == 0u) return RQ_NONE;
        if (dec->esi[v - 1u] == esi) return v - 1u;
        h = (h + 1u) & dec->hash_mask;
    }
}

asx_status asx_raptorq_decoder_add_symbol(asx_raptorq_decoder *dec, uint32_t esi,
                                          const uint8_t *symbol, size_t symbol_len) {
    uint32_t h;
    if (dec == NULL || symbol == NULL || esi > ASX_RAPTORQ_MAX_ESI) {
        return ASX_E_INVALID_ARGUMENT;
    }
    if (dec->ready != RQ_READY) return ASX_E_INVALID_STATE;
    if (symbol_len != dec->symbol_size) return ASX_E_INVALID_ARGUMENT;
    if (rq_decoder_find(dec, esi) != RQ_NONE) return ASX_E_DUPLICATE_SYMBOL;
    if (dec->count >= dec->capacity) return ASX_E_BUFFER_TOO_SMALL;

    dec->esi[dec->count] = esi;
    memcpy(dec->symbols + (size_t)dec->count * dec->symbol_size, symbol, dec->symbol_size);
    h = rq_hash_of(esi, dec->hash_mask);
    while (dec->hash[h] != 0u) h = (h + 1u) & dec->hash_mask;
    dec->hash[h] = dec->count + 1u;
    dec->count++;
    if (esi < dec->params.k) dec->source_count++;
    return ASX_OK;
}

asx_status asx_raptorq_decoder_decode(asx_raptorq_decoder *dec, uint8_t *out, size_t out_len) {
    const asx_raptorq_params *p;
    size_t t;
    rq_arena a;
    rq_solver sv;
    uint32_t i;
    uint32_t n;
    asx_status st;

    if (dec == NULL || out == NULL) return ASX_E_INVALID_ARGUMENT;
    if (dec->ready != RQ_READY) return ASX_E_INVALID_STATE;
    p = &dec->params;
    t = dec->symbol_size;
    if (out_len / t < p->k) return ASX_E_BUFFER_TOO_SMALL;
    if (dec->count < p->k) return ASX_E_RESOURCE_EXHAUSTED;

    if (dec->source_count == p->k) {
        for (i = 0u; i < dec->count; i++) {
            uint32_t esi = dec->esi[i];
            if (esi < p->k) memcpy(out + (size_t)esi * t, dec->symbols + (size_t)i * t, t);
        }
        return ASX_OK;
    }

    n = dec->count + (p->k_prime - p->k);
    rq_arena_init(&a, dec->solver, dec->solver_size);
    st = rq_solver_carve(&a, p, t, n, &sv);
    if (st != ASX_OK) return ASX_E_INVALID_STATE;
    for (i = 0u; i < dec->count; i++) {
        uint32_t esi = dec->esi[i];
        sv.src[i].isi = esi < p->k ? esi : esi + (p->k_prime - p->k);
        sv.src[i].data = dec->symbols + (size_t)i * t;
        sv.src[i].len = t;
    }
    for (i = p->k; i < p->k_prime; i++) {
        rq_src_row *row = &sv.src[dec->count + (i - p->k)];
        row->isi = i;
        row->data = NULL;
        row->len = 0u;
    }
    st = rq_solve(&sv);
    if (st != ASX_OK) return st;

    for (i = 0u; i < p->k; i++) {
        uint32_t idx = rq_decoder_find(dec, i);
        if (idx != RQ_NONE) {
            memcpy(out + (size_t)i * t, dec->symbols + (size_t)idx * t, t);
        } else {
            rq_enc(p, sv.inter, t, i, out + (size_t)i * t);
        }
    }
    return ASX_OK;
}

