/* Solver                                                              */
/* ------------------------------------------------------------------ */

/* Right-hand side of one LT row: the received/source symbol data. */
typedef struct {
    const uint8_t *data; /* NULL: all-zero symbol (padding) */
    size_t len;          /* bytes available at data (<= T); the rest is zero */
    uint32_t isi;
} rq_src_row;

typedef struct {
    const asx_raptorq_params *prm;
    size_t t;            /* symbol size */
    uint32_t n;          /* LT rows */
    uint32_t mb;         /* binary rows: S LDPC rows then n LT rows */
    uint32_t nnz_cap;    /* capacity of row_cols / col_rows */
    uint32_t deg_cap;    /* largest possible active row degree */
    size_t words_cap;    /* 64-bit words per bit vector over L columns */
    rq_src_row *src;     /* [n] */
    uint32_t *row_start; /* [mb + 1] */
    uint32_t *row_cols;  /* [nnz_cap] */
    uint32_t *col_start; /* [W + 1] */
    uint32_t *col_fill;  /* [W] */
    uint32_t *col_rows;  /* [nnz_cap] */
    uint32_t *row_deg;   /* [mb] */
    uint32_t *row_next;  /* [mb] */
    uint32_t *row_prev;  /* [mb] */
    uint8_t *row_state;  /* [mb] */
    uint32_t *bucket;    /* [deg_cap + 1] */
    uint8_t *col_state;  /* [L] */
    uint32_t *col_aux;   /* [L] pivot position or inactive index */
    uint32_t *piv_row;   /* [L] */
    uint32_t *piv_col;   /* [L] */
    uint32_t *inact;     /* [L] inactive index -> column */
    uint32_t *remain;    /* [mb] non-pivot binary rows */
    uint32_t *basis_piv; /* [L] basis row -> pivot inactive index */
    uint32_t *col_basis; /* [L] inactive index -> basis row */
    uint64_t *bits;      /* [L * words_cap] pivot vectors then basis rows */
    uint64_t *row_bits;  /* [words_cap] */
    uint8_t *hcoef;      /* [H * L] */
    uint8_t *gcoef;      /* [L] */
    uint8_t *inter;      /* [L * T] intermediate symbols */
    uint8_t *rhs;        /* [T] */
    uint8_t *hrhs;       /* [H * T] */
    uint8_t *gsym;       /* [T] */
    uint32_t npiv;
    uint32_t ninact;
    uint32_t nremain;
} rq_solver;

/* Lay out (or measure) the solver for `n` LT rows of `t`-byte symbols. */
static asx_status rq_solver_carve(rq_arena *a, const asx_raptorq_params *p, size_t t, uint32_t n,
                                  rq_solver *sv) {
    uint64_t nnz;
    uint32_t ldpc_runs;
    size_t l;
    size_t w;
    size_t mb;

    memset(sv, 0, sizeof(*sv));
    if (!rq_params_valid(p) || t == 0u) return ASX_E_INVALID_ARGUMENT;
    l = p->l;
    w = p->w;
    if ((uint64_t)n + p->s >= (uint64_t)RQ_NONE) return ASX_E_RESOURCE_EXHAUSTED;
    nnz = 3u * (uint64_t)p->b + 3u * (uint64_t)p->s + (uint64_t)RQ_MAX_ROW_ENTRIES * n;
    if (nnz >= (uint64_t)RQ_NONE) return ASX_E_RESOURCE_EXHAUSTED;
    ldpc_runs = (p->b + p->s - 1u) / p->s;

    sv->prm = p;
    sv->t = t;
    sv->n = n;
    sv->mb = p->s + n;
    sv->nnz_cap = (uint32_t)nnz;
    sv->deg_cap = 3u * ldpc_runs + 1u;
    if (sv->deg_cap < RQ_MAX_LT_DEGREE) sv->deg_cap = RQ_MAX_LT_DEGREE;
    sv->words_cap = (l + 63u) / 64u;
    mb = sv->mb;

    sv->src = (rq_src_row *)rq_take(a, n, sizeof(rq_src_row));
    sv->row_start = (uint32_t *)rq_take(a, mb + 1u, sizeof(uint32_t));
    sv->row_cols = (uint32_t *)rq_take(a, sv->nnz_cap, sizeof(uint32_t));
    sv->col_start = (uint32_t *)rq_take(a, w + 1u, sizeof(uint32_t));
    sv->col_fill = (uint32_t *)rq_take(a, w, sizeof(uint32_t));
    sv->col_rows = (uint32_t *)rq_take(a, sv->nnz_cap, sizeof(uint32_t));
    sv->row_deg = (uint32_t *)rq_take(a, mb, sizeof(uint32_t));
    sv->row_next = (uint32_t *)rq_take(a, mb, sizeof(uint32_t));
    sv->row_prev = (uint32_t *)rq_take(a, mb, sizeof(uint32_t));
    sv->row_state = (uint8_t *)rq_take(a, mb, 1u);
    sv->bucket = (uint32_t *)rq_take(a, (size_t)sv->deg_cap + 1u, sizeof(uint32_t));
    sv->col_state = (uint8_t *)rq_take(a, l, 1u);
    sv->col_aux = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    sv->piv_row = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    sv->piv_col = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    sv->inact = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    sv->remain = (uint32_t *)rq_take(a, mb, sizeof(uint32_t));
    sv->basis_piv = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    sv->col_basis = (uint32_t *)rq_take(a, l, sizeof(uint32_t));
    if (sv->words_cap != 0u && l > SIZE_MAX / sv->words_cap) return ASX_E_RESOURCE_EXHAUSTED;
    sv->bits = (uint64_t *)rq_take(a, l * sv->words_cap, sizeof(uint64_t));
    sv->row_bits = (uint64_t *)rq_take(a, sv->words_cap, sizeof(uint64_t));
    sv->hcoef = (uint8_t *)rq_take(a, (size_t)p->h, l);
    sv->gcoef = (uint8_t *)rq_take(a, l, 1u);
    sv->inter = (uint8_t *)rq_take(a, l, t);
    sv->rhs = (uint8_t *)rq_take(a, 1u, t);
    sv->hrhs = (uint8_t *)rq_take(a, (size_t)p->h, t);
    sv->gsym = (uint8_t *)rq_take(a, 1u, t);
    return a->failed ? ASX_E_RESOURCE_EXHAUSTED : ASX_OK;
}

static void rq_load_row_rhs(const rq_solver *sv, uint32_t r, uint8_t *dst) {
    const rq_src_row *s;
    if (r < sv->prm->s) {
        memset(dst, 0, sv->t);
        return;
    }
    s = &sv->src[r - sv->prm->s];
    if (s->data == NULL || s->len == 0u) {
        memset(dst, 0, sv->t);
        return;
    }
    memcpy(dst, s->data, s->len);
    if (s->len < sv->t) memset(dst + s->len, 0, sv->t - s->len);
}

static uint8_t *rq_sym(const rq_solver *sv, uint32_t col) {
    return sv->inter + (size_t)col * sv->t;
}

/* Build the sparse binary rows (LDPC then LT) and the column index. */
static asx_status rq_build_rows(rq_solver *sv) {
    const asx_raptorq_params *p = sv->prm;
    uint32_t *cursor = sv->row_deg; /* temporary */
    uint32_t tg[3];
    uint32_t nt;
    uint32_t i;
    uint32_t e;
    uint32_t r;
    uint32_t pos;
    uint32_t extra = p->p > 1u ? 3u : 1u; /* identity + two PI entries */

    for (r = 0u; r <= p->s; r++) sv->row_start[r] = 0u;
    for (i = 0u; i < p->b; i++) {
        nt = rq_ldpc_targets(i, p->s, tg);
        for (e = 0u; e < nt; e++) sv->row_start[tg[e] + 1u] += 1u;
    }
    for (r = 0u; r < p->s; r++) sv->row_start[r + 1u] += extra + sv->row_start[r];
    for (r = 0u; r < p->s; r++) cursor[r] = sv->row_start[r];
    for (i = 0u; i < p->b; i++) {
        nt = rq_ldpc_targets(i, p->s, tg);
        for (e = 0u; e < nt; e++) sv->row_cols[cursor[tg[e]]++] = i;
    }
    for (r = 0u; r < p->s; r++) {
        sv->row_cols[cursor[r]++] = p->b + r;
        if (p->p > 1u) {
            sv->row_cols[cursor[r]++] = p->w + r % p->p;
            sv->row_cols[cursor[r]++] = p->w + (r + 1u) % p->p;
        }
    }

    pos = sv->row_start[p->s];
    for (r = 0u; r < sv->n; r++) {
        uint32_t idx[RQ_MAX_ROW_ENTRIES];
        uint32_t cnt = rq_lt_indices(p, sv->src[r].isi, idx);
        if (cnt > sv->nnz_cap - pos) return ASX_E_INVALID_STATE;
        memcpy(&sv->row_cols[pos], idx, (size_t)cnt * sizeof(uint32_t));
        pos += cnt;
        sv->row_start[p->s + r + 1u] = pos;
    }

    /* Active degrees and the column -> rows index for columns < W. */
    for (i = 0u; i <= p->w; i++) sv->col_start[i] = 0u;
    for (r = 0u; r < sv->mb; r++) {
        uint32_t deg = 0u;
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (c < p->w) {
                deg++;
                sv->col_start[c + 1u] += 1u;
            }
        }
        if (deg > sv->deg_cap) return ASX_E_INVALID_STATE;
        sv->row_deg[r] = deg;
    }
    for (i = 0u; i < p->w; i++) {
        sv->col_start[i + 1u] += sv->col_start[i];
        sv->col_fill[i] = sv->col_start[i];
    }
    for (r = 0u; r < sv->mb; r++) {
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (c < p->w) sv->col_rows[sv->col_fill[c]++] = r;
        }
    }
    return ASX_OK;
}

static void rq_bucket_push(rq_solver *sv, uint32_t r, uint32_t d) {
    uint32_t head = sv->bucket[d];
    sv->row_prev[r] = RQ_NONE;
    sv->row_next[r] = head;
    if (head != RQ_NONE) sv->row_prev[head] = r;
    sv->bucket[d] = r;
}

static void rq_bucket_remove(rq_solver *sv, uint32_t r, uint32_t d) {
    uint32_t pr = sv->row_prev[r];
    uint32_t nx = sv->row_next[r];
    if (pr != RQ_NONE) {
        sv->row_next[pr] = nx;
    } else {
        sv->bucket[d] = nx;
    }
    if (nx != RQ_NONE) sv->row_prev[nx] = pr;
}

/* Column c stops being active: lower the degree of every row in play. */
static void rq_retire_column(rq_solver *sv, uint32_t c) {
    uint32_t e;
    for (e = sv->col_start[c]; e < sv->col_start[c + 1u]; e++) {
        uint32_t r = sv->col_rows[e];
        uint32_t d;
        if (sv->row_state[r] != RQ_ROW_PLAY) continue;
        d = sv->row_deg[r];
        rq_bucket_remove(sv, r, d);
        d -= 1u;
        sv->row_deg[r] = d;
        if (d == 0u) {
            sv->row_state[r] = RQ_ROW_REMAIN;
            sv->remain[sv->nremain++] = r;
        } else {
            rq_bucket_push(sv, r, d);
        }
    }
}

static void rq_inactivate(rq_solver *sv, uint32_t c) {
    sv->col_state[c] = RQ_COL_INACTIVE;
    sv->col_aux[c] = sv->ninact;
    sv->inact[sv->ninact++] = c;
    rq_retire_column(sv, c);
}

/* Phase 1: peeling with inactivation. */
static asx_status rq_peel(rq_solver *sv) {
    const asx_raptorq_params *p = sv->prm;
    uint32_t active = p->w;
    uint32_t r;
    uint32_t c;
    uint32_t e;
    uint32_t d;

    for (d = 0u; d <= sv->deg_cap; d++) sv->bucket[d] = RQ_NONE;
    sv->npiv = 0u;
    sv->ninact = 0u;
    sv->nremain = 0u;
    for (c = 0u; c < p->l; c++) {
        if (c < p->w) {
            sv->col_state[c] = RQ_COL_ACTIVE;
            sv->col_aux[c] = RQ_NONE;
        } else {
            sv->col_state[c] = RQ_COL_INACTIVE;
            sv->col_aux[c] = sv->ninact;
            sv->inact[sv->ninact++] = c;
        }
    }
    for (r = sv->mb; r-- > 0u;) {
        sv->row_state[r] = RQ_ROW_PLAY;
        if (sv->row_deg[r] == 0u) {
            sv->row_state[r] = RQ_ROW_REMAIN;
            sv->remain[sv->nremain++] = r;
        } else {
            rq_bucket_push(sv, r, sv->row_deg[r]);
        }
    }

    while (active > 0u) {
        r = sv->bucket[1];
        if (r != RQ_NONE) {
            rq_bucket_remove(sv, r, 1u);
            sv->row_state[r] = RQ_ROW_PIVOT;
            c = RQ_NONE;
            for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
                uint32_t cc = sv->row_cols[e];
                if (cc < p->w && sv->col_state[cc] == RQ_COL_ACTIVE) {
                    c = cc;
                    break;
                }
            }
            if (c == RQ_NONE) return ASX_E_INVALID_STATE;
            sv->col_state[c] = RQ_COL_DECIDED;
            sv->col_aux[c] = sv->npiv;
            sv->piv_row[sv->npiv] = r;
            sv->piv_col[sv->npiv] = c;
            sv->npiv++;
            active--;
            rq_retire_column(sv, c);
            continue;
        }

        for (d = 2u; d <= sv->deg_cap && sv->bucket[d] == RQ_NONE; d++) {}
        if (d > sv->deg_cap) {
            /* No row covers the remaining active columns. */
            for (c = 0u; c < p->w; c++) {
                if (sv->col_state[c] == RQ_COL_ACTIVE) rq_inactivate(sv, c);
            }
            break;
        }
        r = sv->bucket[d];
        {
            uint32_t best = RQ_NONE;
            uint32_t best_deg = 0u;
            for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
                uint32_t cc = sv->row_cols[e];
                uint32_t cd;
                if (cc >= p->w || sv->col_state[cc] != RQ_COL_ACTIVE) continue;
                cd = sv->col_start[cc + 1u] - sv->col_start[cc];
                if (best == RQ_NONE || cd > best_deg || (cd == best_deg && cc < best)) {
                    best = cc;
                    best_deg = cd;
                }
            }
            if (best == RQ_NONE) return ASX_E_INVALID_STATE;
            rq_inactivate(sv, best);
            active--;
        }
    }
    if (sv->npiv + sv->ninact != p->l) return ASX_E_INVALID_STATE;
    return ASX_OK;
}

/* Solve A * C = D for the intermediate symbols. Returns ASX_OK,
 * ASX_E_RESOURCE_EXHAUSTED when the rows are rank-deficient, or
 * ASX_E_INVALID_STATE on an internal consistency failure. */
static asx_status rq_solve(rq_solver *sv) {
    const asx_raptorq_params *p = sv->prm;
    const size_t t = sv->t;
    size_t words;
    uint64_t *vec;
    uint64_t *basis;
    uint32_t ti;
    uint32_t q;
    uint32_t e;
    uint32_t nb = 0u;
    uint32_t nfree;
    uint32_t free_cols[RQ_MAX_H];
    asx_status st;

    st = rq_build_rows(sv);
    if (st != ASX_OK) return st;
    st = rq_peel(sv);
    if (st != ASX_OK) return st;

    words = ((size_t)sv->ninact + 63u) / 64u;
    if (words > sv->words_cap || ((size_t)sv->npiv + sv->ninact) > p->l) {
        return ASX_E_INVALID_STATE;
    }
    vec = sv->bits;
    basis = sv->bits + (size_t)sv->npiv * words;

    /* Phase 2: each decided column as a GF(2) combination of I. */
    for (ti = 0u; ti < sv->npiv; ti++) {
        uint64_t *v = vec + (size_t)ti * words;
        uint32_t r = sv->piv_row[ti];
        uint32_t c0 = sv->piv_col[ti];
        memset(v, 0, words * sizeof(uint64_t));
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (c == c0) continue;
            if (sv->col_state[c] == RQ_COL_INACTIVE) {
                rq_bit_flip(v, sv->col_aux[c]);
            } else if (sv->col_state[c] == RQ_COL_DECIDED && sv->col_aux[c] < ti) {
                rq_bits_xor(v, vec + (size_t)sv->col_aux[c] * words, words);
            } else {
                return ASX_E_INVALID_STATE;
            }
        }
    }

    /* Phase 3: partial decided values assuming C[I] = 0. */
    memset(sv->inter, 0, (size_t)p->l * t);
    for (ti = 0u; ti < sv->npiv; ti++) {
        uint32_t r = sv->piv_row[ti];
        uint32_t c0 = sv->piv_col[ti];
        uint8_t *dst = rq_sym(sv, c0);
        rq_load_row_rhs(sv, r, dst);
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (c != c0 && sv->col_state[c] == RQ_COL_DECIDED) rq_sym_xor(dst, rq_sym(sv, c), t);
        }
    }

    /* Phase 4: binary non-pivot rows reduced into a GF(2) basis (RREF).
     * The right-hand side of the basis row with pivot k lives in the
     * intermediate-symbol slot of inactive column inact[k]. */
    for (q = 0u; q < sv->ninact; q++) sv->col_basis[q] = RQ_NONE;
    for (q = 0u; q < sv->nremain && nb < sv->ninact; q++) {
        uint32_t r = sv->remain[q];
        uint64_t *rb = sv->row_bits;
        uint32_t pk;
        uint32_t bi;
        memset(rb, 0, words * sizeof(uint64_t));
        rq_load_row_rhs(sv, r, sv->rhs);
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (sv->col_state[c] == RQ_COL_INACTIVE) {
                rq_bit_flip(rb, sv->col_aux[c]);
            } else {
                rq_bits_xor(rb, vec + (size_t)sv->col_aux[c] * words, words);
                rq_sym_xor(sv->rhs, rq_sym(sv, c), t);
            }
        }
        for (bi = 0u; bi < nb; bi++) {
            uint32_t bp = sv->basis_piv[bi];
            if (rq_bit_get(rb, bp)) {
                rq_bits_xor(rb, basis + (size_t)bi * words, words);
                rq_sym_xor(sv->rhs, rq_sym(sv, sv->inact[bp]), t);
            }
        }
        pk = rq_bits_lowest(rb, words);
        if (pk == RQ_NONE) continue; /* redundant row */
        for (bi = 0u; bi < nb; bi++) {
            uint64_t *brow = basis + (size_t)bi * words;
            if (rq_bit_get(brow, pk)) {
                rq_bits_xor(brow, rb, words);
                rq_sym_xor(rq_sym(sv, sv->inact[sv->basis_piv[bi]]), sv->rhs, t);
            }
        }
        memcpy(basis + (size_t)nb * words, rb, words * sizeof(uint64_t));
        memcpy(rq_sym(sv, sv->inact[pk]), sv->rhs, t);
        sv->basis_piv[nb] = pk;
        sv->col_basis[pk] = nb;
        nb++;
    }

    /* Phase 5: HDPC rows for the inactive columns the binary rows miss. */
    nfree = sv->ninact - nb;
    if (nfree > p->h) return ASX_E_RESOURCE_EXHAUSTED;
    if (nfree > 0u) {
        const uint32_t ks = p->k_prime + p->s;
        const size_t ni = sv->ninact;
        uint32_t j;
        uint32_t i;
        uint32_t m;
        uint32_t used = 0u; /* bitmask of HDPC rows chosen as pivots */
        uint32_t prow[RQ_MAX_H];

        memset(sv->hcoef, 0, (size_t)p->h * ni);
        memset(sv->gcoef, 0, ni);
        memset(sv->hrhs, 0, (size_t)p->h * t);
        memset(sv->gsym, 0, t);
        for (j = 0u; j < ks; j++) {
            size_t k;
            for (k = 0u; k < ni; k++) sv->gcoef[k] = rq_gf_mul2(sv->gcoef[k]);
            rq_sym_mul2(sv->gsym, t);
            if (sv->col_state[j] == RQ_COL_DECIDED) {
                const uint64_t *v = vec + (size_t)sv->col_aux[j] * words;
                size_t wi;
                for (wi = 0u; wi < words; wi++) {
                    uint64_t wv = v[wi];
                    while (wv != 0u) {
                        sv->gcoef[wi * 64u + rq_ctz64(wv)] ^= 1u;
                        wv &= wv - 1u;
                    }
                }
                rq_sym_xor(sv->gsym, rq_sym(sv, j), t);
            } else {
                sv->gcoef[sv->col_aux[j]] ^= 1u;
            }
            if (j + 1u < ks) {
                uint32_t h1 = asx_raptorq_rand(j + 1u, 6u, p->h);
                uint32_t h2 = (h1 + asx_raptorq_rand(j + 1u, 7u, p->h - 1u) + 1u) % p->h;
                rq_sym_xor(sv->hcoef + (size_t)h1 * ni, sv->gcoef, ni);
                rq_sym_xor(sv->hcoef + (size_t)h2 * ni, sv->gcoef, ni);
                rq_sym_xor(sv->hrhs + (size_t)h1 * t, sv->gsym, t);
                rq_sym_xor(sv->hrhs + (size_t)h2 * t, sv->gsym, t);
            } else {
                for (i = 0u; i < p->h; i++) {
                    uint8_t f = rq_oct_exp[i];
                    rq_sym_muladd(sv->hcoef + (size_t)i * ni, sv->gcoef, f, ni);
                    rq_sym_muladd(sv->hrhs + (size_t)i * t, sv->gsym, f, t);
                }
            }
        }
        for (i = 0u; i < p->h; i++) {
            uint32_t col = ks + i; /* HDPC identity column (PI, inactive) */
            sv->hcoef[(size_t)i * ni + sv->col_aux[col]] ^= 1u;
        }

        /* Reduce HDPC rows by the RREF binary basis. */
        for (i = 0u; i < p->h; i++) {
            uint8_t *hc = sv->hcoef + (size_t)i * ni;
            uint32_t bi;
            for (bi = 0u; bi < nb; bi++) {
                uint32_t bp = sv->basis_piv[bi];
                uint8_t f = hc[bp];
                const uint64_t *brow = basis + (size_t)bi * words;
                size_t wi;
                if (f == 0u) continue;
                for (wi = 0u; wi < words; wi++) {
                    uint64_t wv = brow[wi];
                    while (wv != 0u) {
                        hc[wi * 64u + rq_ctz64(wv)] ^= f;
                        wv &= wv - 1u;
                    }
                }
                rq_sym_muladd(sv->hrhs + (size_t)i * t, rq_sym(sv, sv->inact[bp]), f, t);
            }
        }

        /* GF(256) Gauss-Jordan over the free columns. */
        m = 0u;
        for (q = 0u; q < sv->ninact; q++) {
            if (sv->col_basis[q] == RQ_NONE) free_cols[m++] = q;
        }
        for (m = 0u; m < nfree; m++) {
            uint32_t k = free_cols[m];
            uint32_t piv = RQ_NONE;
            uint32_t m2;
            uint8_t inv;
            uint8_t *prc;
            for (i = 0u; i < p->h; i++) {
                if ((used & (1u << i)) == 0u && sv->hcoef[(size_t)i * ni + k] != 0u) {
                    piv = i;
                    break;
                }
            }
            if (piv == RQ_NONE) return ASX_E_RESOURCE_EXHAUSTED;
            used |= 1u << piv;
            prow[m] = piv;
            prc = sv->hcoef + (size_t)piv * ni;
            inv = rq_gf_inv(prc[k]);
            for (m2 = 0u; m2 < nfree; m2++) prc[free_cols[m2]] = rq_gf_mul(prc[free_cols[m2]], inv);
            rq_sym_scale(sv->hrhs + (size_t)piv * t, inv, t);
            for (i = 0u; i < p->h; i++) {
                uint8_t *orc = sv->hcoef + (size_t)i * ni;
                uint8_t g = orc[k];
                if (i == piv || g == 0u) continue;
                for (m2 = 0u; m2 < nfree; m2++) {
                    orc[free_cols[m2]] ^= rq_gf_mul(g, prc[free_cols[m2]]);
                }
                rq_sym_muladd(sv->hrhs + (size_t)i * t, sv->hrhs + (size_t)piv * t, g, t);
            }
        }
        for (m = 0u; m < nfree; m++) {
            memcpy(rq_sym(sv, sv->inact[free_cols[m]]), sv->hrhs + (size_t)prow[m] * t, t);
        }
        /* Back-substitute the free columns into the binary basis rows. */
        for (q = 0u; q < nb; q++) {
            const uint64_t *brow = basis + (size_t)q * words;
            uint8_t *dst = rq_sym(sv, sv->inact[sv->basis_piv[q]]);
            for (m = 0u; m < nfree; m++) {
                if (rq_bit_get(brow, free_cols[m])) {
                    rq_sym_xor(dst, rq_sym(sv, sv->inact[free_cols[m]]), t);
                }
            }
        }
    }

    /* Phase 6: forward substitution with the solved inactive symbols. */
    for (ti = 0u; ti < sv->npiv; ti++) {
        uint32_t r = sv->piv_row[ti];
        uint32_t c0 = sv->piv_col[ti];
        uint8_t *dst = rq_sym(sv, c0);
        rq_load_row_rhs(sv, r, dst);
        for (e = sv->row_start[r]; e < sv->row_start[r + 1u]; e++) {
            uint32_t c = sv->row_cols[e];
            if (c != c0) rq_sym_xor(dst, rq_sym(sv, c), t);
        }
    }
    return ASX_OK;
}

